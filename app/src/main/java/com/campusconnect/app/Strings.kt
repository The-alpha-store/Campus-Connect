package com.campusconnect.app

import java.util.Locale

/** Current UI language. Set once at the root; changing it rebuilds the UI. */
object Lang {
    @Volatile var sw: Boolean = false
        private set
    @Volatile var locale: Locale = Locale.ENGLISH
        private set

    fun set(code: String) {
        sw = code == "sw"
        locale = if (sw) Locale.forLanguageTag("sw-TZ") else Locale.ENGLISH
    }
}

/** Translate a UI string. English is the key; unknown strings fall back to English. */
fun tr(en: String): String = if (Lang.sw) (Sw[en] ?: en) else en

/** Translate a format string, then fill in the values. */
fun trf(en: String, vararg args: Any?): String = String.format(Lang.locale, tr(en), *args)

